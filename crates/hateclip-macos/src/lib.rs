//! macOS system integration. On other platforms every function is a no-op so
//! the rest of the workspace still builds and tests there.

#[cfg(target_os = "macos")]
mod imp;
#[cfg(not(target_os = "macos"))]
mod stub;

#[cfg(target_os = "macos")]
pub use imp::*;
#[cfg(not(target_os = "macos"))]
pub use stub::*;

/// The application that was frontmost when something happened.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppInfo {
    pub bundle_id: Option<String>,
    pub name: Option<String>,
    pub pid: i32,
}

/// What the clipboard currently holds, from our point of view.
#[derive(Debug)]
pub enum ReadResult {
    /// Nothing we can record.
    Empty,
    /// A password manager or similar marked the content as secret or transient.
    Concealed,
    Content(hateclip_core::Capture),
}

/// Pasteboard types that well-behaved apps set to ask clipboard managers not to
/// record the content (see nspasteboard.org).
pub const PRIVATE_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
];

pub const ACCESSIBILITY_SETTINGS_URL: &str =
    "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility";
